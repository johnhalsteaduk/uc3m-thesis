function [lhs, rhs] = static_resid(y, x, params)
T = NaN(4, 1);
lhs = NaN(15, 1);
rhs = NaN(15, 1);
T(1) = 1/y(1);
T(2) = y(3)^params(1);
T(3) = exp(y(8)*(-params(8)))*T(2);
T(4) = y(4)^(1-params(1));
lhs(1) = T(1)*(1+params(12)*(y(2)/y(3)-params(3)));
rhs(1) = T(1)*params(2)*(params(12)*(y(2)/y(3)-params(3))+1+y(5)-params(3));
lhs(2) = y(6)/y(1);
rhs(2) = params(5)*y(4)^params(4);
lhs(3) = y(2);
rhs(3) = y(3)-y(3)*(1-params(3)-params(7)*y(8));
lhs(4) = y(9);
rhs(4) = y(2)+y(1)+y(9)*(1+y(10)*(1-y(11)))-y(7);
lhs(5) = y(7);
rhs(5) = T(3)*T(4);
lhs(6) = y(5);
rhs(6) = y(7)*params(1)/y(3);
lhs(7) = y(6);
rhs(7) = y(7)*(1-params(1))/y(4);
lhs(8) = y(8);
rhs(8) = y(8)*params(6)+x(1);
lhs(9) = T(1);
rhs(9) = (1+y(10)*(1-y(11)))*params(2)/y(1);
lhs(10) = y(10);
rhs(10) = params(11)+params(9)*(y(9)-params(10));
lhs(11) = y(11);
rhs(11) = x(1)+y(12)+y(13)+y(14)+y(15);
lhs(12) = y(12);
rhs(12) = x(1);
lhs(13) = y(13);
rhs(13) = y(12);
lhs(14) = y(14);
rhs(14) = y(13);
lhs(15) = y(15);
rhs(15) = y(14);
end
