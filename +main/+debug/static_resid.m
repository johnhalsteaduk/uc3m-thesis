function [lhs, rhs] = static_resid(y, x, params)
T = NaN(3, 1);
lhs = NaN(8, 1);
rhs = NaN(8, 1);
T(1) = y(3)^params(1);
T(2) = exp(y(8)*(-params(9)))*T(1);
T(3) = y(4)^(1-params(1));
lhs(1) = 1/y(1);
rhs(1) = params(2)/y(1)*(1+y(5)-params(3));
lhs(2) = y(6)/y(1);
rhs(2) = params(6)*y(4)^params(4);
lhs(3) = y(2);
rhs(3) = y(3)-y(3)*(1-params(3)-params(8)*y(8));
lhs(4) = y(7);
rhs(4) = y(1)+y(2);
lhs(5) = y(7);
rhs(5) = T(2)*T(3);
lhs(6) = y(5);
rhs(6) = y(7)*params(1)/y(3);
lhs(7) = y(6);
rhs(7) = y(7)*(1-params(1))/y(4);
lhs(8) = y(8);
rhs(8) = y(8)*params(7)+x(1);
end
