lhs(1) = 1/y(9);
rhs(1) = params(2)/y(17)*(1+y(21)-params(3));
lhs(2) = y(14)/y(9);
rhs(2) = params(6)*y(12)^params(4);
lhs(3) = y(10);
rhs(3) = y(11)-(1-params(3)-params(8)*y(16))*y(3);
lhs(4) = y(15);
rhs(4) = y(9)+y(10);
lhs(5) = y(15);
rhs(5) = T(2)*T(3);
lhs(6) = y(13);
