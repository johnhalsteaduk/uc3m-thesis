function [lhs, rhs] = static_resid(y, x, params)
T = NaN(4, 1);
lhs = NaN(10, 1);
rhs = NaN(10, 1);
T(1) = exp(y(1))*y(4)^params(1);
T(2) = y(5)^(1-params(1));
T(3) = y(9)^params(8);
T(4) = T(1)*T(2)*T(3);
lhs(1) = 1/y(2);
rhs(1) = params(2)/y(2)*(1+y(6)-params(3));
lhs(2) = y(7)/y(2);
rhs(2) = params(6)*y(5)^params(4);
lhs(3) = y(3);
rhs(3) = y(4)-y(4)*(1-params(3));
lhs(4) = y(8);
rhs(4) = y(2)+y(3);
lhs(5) = y(8);
rhs(5) = T(4);
lhs(6) = y(9);
rhs(6) = y(9)*(1-params(3)-params(9))+(1-params(10))*y(10);
lhs(7) = y(10);
rhs(7) = y(8)*params(7);
lhs(8) = y(6);
rhs(8) = y(8)*params(1)/y(4);
lhs(9) = y(7);
rhs(9) = y(8)*(1-params(1))/y(5);
lhs(10) = y(1);
rhs(10) = y(1)*params(5)-x(1);
end
